/**
 * deploy-all.ts — Deploy all 3 DPO2U compliance contracts in a single wallet session
 *
 * Syncs the wallet ONCE and deploys ConsentRegistry, DataAuditLog, and DataSubjectRights
 * in sequence. Running the 3 individual deploy scripts separately would sync the wallet
 * 3 times (potentially 20-60 min each on preprod); this script reduces that to one sync.
 *
 * Usage:
 *   npx tsx scripts/deploy-all.ts [options]
 *
 * Options:
 *   --network   preprod | preview | standalone  (default: standalone)
 *   --seed      <64-char hex>  HD wallet seed (saved to deploy output — store securely!)
 *   --faucet    request tNIGHT from faucet after sync (preprod/preview only)
 *   --skip-cr   skip ConsentRegistry deployment (e.g. already deployed)
 *   --skip-dal  skip DataAuditLog deployment
 *   --skip-dsr  skip DataSubjectRights deployment
 *
 * Prerequisites:
 *   ./scripts/compile-contracts.sh        (compiles all 3 contracts)
 *   npm install                           (rm -f .npmrc first — Bug 2)
 *   docker compose up -d                  (midnight-node, indexer, proof-server)
 *
 * Saves deployment info to (consumed by interact-full-suite.ts):
 *   deployment-consent-registry-<network>.json
 *   deployment-data-audit-log-<network>.json
 *   deployment-data-subject-rights-<network>.json
 *
 * SDK Versions (preprod — SDK-VERSION-MATRIX.md):
 *   @midnight-ntwrk/midnight-js-*       3.0.0–3.1.0
 *   @midnight-ntwrk/wallet-sdk-facade   2.0.0  (WalletFacade.init API)
 *   @midnight-ntwrk/ledger-v7           7.0.0
 *   @midnight-ntwrk/compact-runtime     0.14.0
 *   midnight-node Docker                0.21.0
 *   indexer-standalone Docker           3.1.0
 *   proof-server Docker                 7.0.0
 *
 * CRITICAL RULES from WORKAROUND-GUIDE.md:
 *   - NEVER use npm.midnight.network (does not exist — Bug 2)
 *   - NEVER mix preprod/preview SDK versions (silent sync failures — Bug 3)
 *   - NEVER use wallet.signRecipe() — use WalletFacade.init + finalizeRecipe (Bug 5)
 *   - ALWAYS call setNetworkId() before any contract operation (Bug 4)
 *   - ALWAYS add smoldot override to package.json (Bug 7)
 *   - ALWAYS pass walletProvider to levelPrivateStateProvider (Bug 6)
 */

