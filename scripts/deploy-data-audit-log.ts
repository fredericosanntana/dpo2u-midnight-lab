// ------------------------------------------------------------------
// Demo: LGPD Art. 37 audit event lifecycle
//
// Scenario: "BancoXYZ S.A." (a fictional financial data controller) processes
// personal data of customers. Only the controller's hash goes on-chain — no PII.
//
// Shows:
//   1. logEvent — data_collection (new customer onboarding, type 1)
//   2. logEvent — data_access (query by internal analyst, type 2)
//   3. logEvent — data_transfer_third_party (shared with credit bureau, type 4)
//   4. logDeletionRequest — customer requests erasure (LGPD Art. 18 VI, type 5)
//   5. confirmDeletion — erasure completed within 15 days (type 6)
//   6. logBreachEvent — security incident reported to ANPD (LGPD Art. 48, type 9)
//   7. Query all counters and per-controller state
// ------------------------------------------------------------------
async function runDemo(contract: any, deployBlock: number) {
  console.log('\n--- Demo: LGPD Art. 37 Data Processing Audit Trail ---');

  // Controller identifier — only the hash goes on-chain (no PII)
  const controllerName = 'BancoXYZ S.A. CNPJ 00.000.001/0001-00';
  const controllerId = createHash('sha256').update(controllerName).digest();

  // Actor hashes (employees/systems performing actions) — also hashed
  const actorAnalyst = createHash('sha256').update('analyst-system-id-001').digest();
  const actorDPO = createHash('sha256').update('dpo-officer-id-002').digest();

  // Block numbers simulate a timeline of events (Uint<32>: no practical ceiling).
  // In standalone: these can be set to low values for immediate testing.
  // In preprod/preview: use the actual current block height.
  const baseBlock = deployBlock + 1;

  console.log(`\n  Controller: sha256("${controllerName}")`);
  console.log(`  Base block: ${baseBlock}\n`);

  // ---------------------------------------------------------------------------
  // 1. logEvent — data_collection (type 1): new customer personal data received
  // ---------------------------------------------------------------------------
  const block1 = baseBlock;
  console.log(`[1] logEvent(type=1 data_collection, block=${block1})`);
  console.log(`    LGPD Art. 37: recording data collection activity`);
  const r1 = await contract.callTx.logEvent(controllerId, 1, block1);
  console.log(`    Tx: ${r1.public.txId} (block ${r1.public.blockHeight})`);

  // ---------------------------------------------------------------------------
  // 2. logEvent — data_access (type 2): internal analyst queried customer data
  // ---------------------------------------------------------------------------
  const block2 = (block1 + 10) & 0xFFFF;
  console.log(`\n[2] logEvent(type=2 data_access, block=${block2})`);
  console.log(`    LGPD Art. 37: recording internal data access`);
  const r2 = await contract.callTx.logEvent(controllerId, 2, block2);
  console.log(`    Tx: ${r2.public.txId}`);

  // ---------------------------------------------------------------------------
  // 3. logEvent — data_transfer_third_party (type 4): shared with credit bureau
  //    LGPD Art. 7 VIII requires documented legal basis for third-party transfers
  // ---------------------------------------------------------------------------
  const block3 = (block2 + 5) & 0xFFFF;
  console.log(`\n[3] logEvent(type=4 data_transfer_third_party, block=${block3})`);
  console.log(`    LGPD Art. 7 VIII: third-party transfer (legal basis stored off-chain)`);
  const r3 = await contract.callTx.logEvent(controllerId, 4, block3);
  console.log(`    Tx: ${r3.public.txId}`);

  // Query per-controller state after 3 general events
  console.log(`\n[4] getControllerEventCount (after 3 events)`);
  const count4 = await contract.callTx.getControllerEventCount(controllerId);
  console.log(`    Event count: ${count4.data} (expected 3)`);

  console.log(`\n[5] getLastEventType + getLastEventBlock`);
  const lastType = await contract.callTx.getLastEventType(controllerId);
  const lastBlock = await contract.callTx.getLastEventBlock(controllerId);
  console.log(`    Last event type: ${lastType.data} (expected 4 = data_transfer_third_party)`);
  console.log(`    Last event block: ${lastBlock.data} (expected ${block3})`);

  // ---------------------------------------------------------------------------
  // 4. logDeletionRequest — customer exercises LGPD Art. 18 VI right to erasure
  // ---------------------------------------------------------------------------
  const block5 = (block3 + 20) & 0xFFFF;
  console.log(`\n[6] logDeletionRequest(block=${block5})`);
  console.log(`    LGPD Art. 18 VI: deletion request received from data subject`);
  const r5 = await contract.callTx.logDeletionRequest(controllerId, actorDPO, block5);
  console.log(`    Tx: ${r5.public.txId}`);

  // ---------------------------------------------------------------------------
  // 5. confirmDeletion — DPO confirms erasure within LGPD 15-day window
  //    LGPD requires response within 15 days of the request
  // ---------------------------------------------------------------------------
  const block6 = (block5 + 100) & 0xFFFF;  // 100 blocks ≈ 100 minutes — well within 15 days
  console.log(`\n[7] confirmDeletion(block=${block6})`);
  console.log(`    LGPD: erasure confirmed ${block6 - block5} blocks after request (< 21600-block deadline)`);
  const r6 = await contract.callTx.confirmDeletion(controllerId, actorDPO, block6);
  console.log(`    Tx: ${r6.public.txId}`);

  // ---------------------------------------------------------------------------
  // 6. logBreachEvent — security incident (LGPD Art. 48: notify ANPD within 2 business days)
  // ---------------------------------------------------------------------------
  const block7 = (block6 + 50) & 0xFFFF;
  console.log(`\n[8] logBreachEvent(block=${block7})`);
  console.log(`    LGPD Art. 48: security breach notification logged for ANPD`);
  const r7 = await contract.callTx.logBreachEvent(controllerId, block7);
  console.log(`    Tx: ${r7.public.txId}`);

  // ---------------------------------------------------------------------------
  // 7. Read all aggregate counters (ANPD audit readiness)
  // ---------------------------------------------------------------------------
  console.log('\n[9] Aggregate counters (ANPD audit readiness)');

  const totalEvents = await contract.callTx.getTotalEvents();
  console.log(`    Total events:              ${totalEvents.data} (expected 6)`);
  // logEvent x3 + logDeletionRequest x1 + confirmDeletion x1 + logBreachEvent x1 = 6

  const totalDeletionRequests = await contract.callTx.getTotalDeletionRequests();
  console.log(`    Total deletion requests:   ${totalDeletionRequests.data} (expected 1)`);

  const totalDeletionsConfirmed = await contract.callTx.getTotalDeletionsConfirmed();
  console.log(`    Total deletions confirmed: ${totalDeletionsConfirmed.data} (expected 1)`);

  const totalBreachEvents = await contract.callTx.getTotalBreachEvents();
  console.log(`    Total breach events:       ${totalBreachEvents.data} (expected 1)`);

  const finalCount = await contract.callTx.getControllerEventCount(controllerId);
  console.log(`    Controller event count:    ${finalCount.data} (expected 6)`);

  console.log('\n    Demo complete ✓');
  console.log('    Note: block_number is Uint<16> — max 65535 (≈45 days at 1 block/min).');
  console.log('          For longer deployments, pass modular block chunks (e.g. block % 65535)');
  console.log('          or use a separate time oracle. See DataAuditLog.compact header.');
}

