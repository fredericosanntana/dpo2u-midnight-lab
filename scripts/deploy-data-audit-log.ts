async function main() {
  const { values } = parseArgs({
    options: {
      network: { type: 'string', default: process.env.MIDNIGHT_NETWORK ?? 'preprod' },
      seed:    { type: 'string' },
      join:    { type: 'string' },
      faucet:  { type: 'boolean', default: false },
      demo:    { type: 'boolean', default: false },
    },
  });

  const net = values.network ?? 'preprod';
  const config = NETWORKS[net];
  if (!config) { console.error(`Unknown network: ${net}`); process.exit(1); }

  console.log('='.repeat(60));
  console.log('  DPO2U DataAuditLog — Midnight Network');
  console.log(`  Network: ${net.toUpperCase()}`);
  console.log('='.repeat(60));
  console.log(`  Indexer:      ${config.indexer}`);
  console.log(`  Proof Server: ${config.proofServer}`);
  console.log(`  ZK Assets:    ${ZK_CONFIG_PATH}`);
  console.log('');

  // CRITICAL: must call setNetworkId() before any contract operation
  setNetworkId(config.networkId);

  const seed = values.seed ?? process.env.MIDNIGHT_SEED ?? toHex(Buffer.from(generateRandomSeed()));
  console.log(`  Seed: ${seed}`);
  console.log('  ⚠️  Save this seed to restore your wallet!\n');

  const ctx = await buildWallet(config, seed);
  const addr = ctx.unshieldedKeystore.getBech32Address();
  console.log(`  Address: ${addr}\n`);

  await waitForSync(ctx.wallet);

  if (values.faucet && config.faucetUrl) {
    await requestFaucet(config.faucetUrl, addr);
  }

  console.log('[4/6] Checking balance...');
  await checkBalance(ctx.wallet);

  const providers = await configureProviders(ctx, config);

  let contract;
  if (values.join) {
    contract = await join(providers, values.join);
  } else {
    contract = await deploy(providers);
  }

  const deployBlock = contract.deployTxData.public.blockHeight as number;

  if (values.demo) {
    await runDemo(contract, deployBlock);
  }

  // Save deployment info
  const deployInfo = {
    contract: 'DataAuditLog',
    network: net,
    contractAddress: contract.deployTxData.public.contractAddress,
    blockHeight: deployBlock,
    txId: contract.deployTxData.public.txId,
    walletAddress: addr,
    timestamp: new Date().toISOString(),
    lgpdCoverage: [
      'Art. 37 (processing activity records, event types 1-9)',
      'Art. 18 VI (deletion request tracking)',
      'Art. 48 (breach notification logging)',
    ],
    sdkVersions: {
      'midnight-js': '3.0.0-3.1.0',
      'wallet-sdk-facade': '2.0.0',
      'compact-runtime': '0.14.0',
      'ledger-v7': '7.0.0',
    },
  };

  console.log('\n' + '='.repeat(60));
  console.log('  DEPLOYMENT SUMMARY');
  console.log('='.repeat(60));
  console.log(`  Network:  ${net}`);
  console.log(`  Contract: ${deployInfo.contractAddress}`);
  console.log(`  Block:    ${deployInfo.blockHeight}`);
  console.log(`  Tx:       ${deployInfo.txId}`);
  console.log(`  Seed:     ${seed}`);
  console.log(`  Address:  ${addr}`);
  console.log('='.repeat(60));

  const deployPath = path.resolve(
    new URL(import.meta.url).pathname,
    '..', '..', `deployment-data-audit-log-${net}.json`,
  );
  fs.writeFileSync(deployPath, JSON.stringify(deployInfo, null, 2));
  console.log(`\n  Saved to: ${deployPath}`);

  await ctx.wallet.stop();
  process.exit(0);
}

main().catch((err) => {
  console.error('\nDeploy failed:', err);
  process.exit(1);
});
